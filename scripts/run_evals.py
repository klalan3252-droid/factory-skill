#!/usr/bin/env python3
"""Run the quantified evals for factory.py and write docs/eval-results.md.

Usage: run_evals.py [--check]   (--check fails if the results doc is stale)
Output is deterministic (no timestamps) so it can be verified in CI.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import factory  # noqa: E402

RESULTS = ROOT / "docs" / "eval-results.md"


def _repo(c):
    return factory.resolve_repo(c["slack"], c["task"])[0]


def _limit(c):
    return factory.parse_limit(c["text"], c["now"])


def _branch(c):
    return factory.branch_name(c["task_id"], c["title"])


def _heal(c):
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "s.json"
        factory.init_state(path, "EVAL")
        calls = {"n": 0}

        def run(_cmd):
            calls["n"] += 1
            ok = calls["n"] > c["fail_times"]
            return SimpleNamespace(returncode=0 if ok else 1, stdout="", stderr="FAIL")

        got = []
        for _ in range(c["max_attempts"] + 1):
            r = factory.heal_once(path, "test", "x", c["max_attempts"], run=run)["result"]
            got.append(r)
            if r in ("pass", "exhausted"):
                break
        return got


def _resume():
    """Crash after every step; a fresh process must resume without redoing work."""
    outcomes = []
    for crash_after in range(len(factory.STEPS)):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "s.json"
            factory.init_state(path, "EVAL")
            executed = []
            for phase in (crash_after, None):  # first process crashes, second finishes
                state = factory.init_state(path, "EVAL")  # reload from disk
                while (step := factory.next_step(state)) is not None:
                    executed.append(step)
                    factory.mark(state, step, "done")
                    factory.save(path, state)
                    if phase is not None and step == factory.STEPS[phase]:
                        break
            ok = executed == factory.STEPS
            # corrupt the primary file: .bak must still allow resume
            path.write_text("{not json")
            ok = ok and factory.load(path) is not None
            outcomes.append(ok)
    return outcomes


def _pause_resume():
    """Limit hit mid-test: paused without using an attempt, wait, then resume."""
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "s.json"
        factory.init_state(path, "EVAL")
        replies = [SimpleNamespace(returncode=1, stdout="usage limit reached. Retry-After: 100", stderr=""),
                   SimpleNamespace(returncode=0, stdout="ok", stderr="")]
        r1 = factory.heal_once(path, "test", "x", 3, run=lambda c: replies.pop(0), now=1000)
        st = factory.load(path)
        paused_ok = (r1["result"] == "paused" and st["status"] == "paused"
                     and st["steps"]["test"]["attempts"] == 0 and r1["resume_at"] == 1130)
        clock = {"t": 1000.0}
        factory.wait_until(r1["resume_at"], sleep=lambda s: clock.__setitem__("t", clock["t"] + s),
                           clock=lambda: clock["t"])
        r2 = factory.heal_once(path, "test", "x", 3, run=lambda c: replies.pop(0))
        return [paused_ok, clock["t"] >= 1130, r2["result"] == "pass"]


def _redaction():
    secrets = ["ghp_" + "a" * 36, "xoxb-1234567890-abcdefghij", "sk-" + "b" * 30]
    rep = factory.failure_report("open PR", "denied " + " ".join(secrets),
                                 "gh pr create https://github.com/a/b/pull/7", "retry")
    return [s not in rep for s in secrets] + ["/pull/" not in rep]


def run():
    cases = json.loads((ROOT / "evals" / "cases.json").read_text())
    table = []
    for name, fn, key in (("Repo resolution", _repo, "repo_resolution"),
                          ("Usage-limit reset parsing", _limit, "usage_limit_parsing"),
                          ("Branch naming", _branch, "branch_naming"),
                          ("Self-healing loop", _heal, "self_healing")):
        results = [fn(c) == c["expect"] for c in cases[key]]
        table.append((name, sum(results), len(results)))
    for name, outcomes in (("Crash/resume at every step + corrupt-file recovery", _resume()),
                           ("Usage-limit pause then resume", _pause_resume()),
                           ("Secret redaction / no PR link in failure report", _redaction())):
        table.append((name, sum(outcomes), len(outcomes)))
    return table


def render(table):
    total, passed = sum(t for _, _, t in table), sum(p for _, p, _ in table)
    lines = ["# Eval results", "",
             "Generated by `python3 -I scripts/run_evals.py`; cases live in `evals/cases.json`.",
             "Do not edit by hand: the test suite fails if this file is stale.", "",
             "| Eval | Passed | Total | Score |", "| --- | --- | --- | --- |"]
    lines += [f"| {n} | {p} | {t} | {100 * p // t}% |" for n, p, t in table]
    lines += [f"| **All** | **{passed}** | **{total}** | **{100 * passed // total}%** |", ""]
    return "\n".join(lines)


def main():
    out = render(run())
    if "--check" in sys.argv:
        if not RESULTS.exists() or RESULTS.read_text() != out:
            print("docs/eval-results.md is stale; run scripts/run_evals.py", file=sys.stderr)
            return 1
        return 0
    RESULTS.write_text(out)
    print(out)
    return 0 if all(p == t for _, p, t in run()) else 1


if __name__ == "__main__":
    sys.exit(main())
